"""agents/config/osquery.conf as Fleet specs (#14): what an agent enrolled in Fleet runs, generated so the two can't drift.

    python tools/fleet_config.py > deploy/fleet/tapwatch.yml      # tests/test_fleet.py checks it is current
    fleetctl apply -f deploy/fleet/tapwatch.yml

A standalone agent reads osquery.conf from disk. An enrolled one gets its config from Fleet: the `options` and
`file_paths` become Fleet's agent options, and every scheduled query becomes a Fleet query with automations on
(its results go to Fleet's results log, which tapwatch follows) and `discard_data` (Fleet keeps no copy; tapwatch
has them). Fleet sends the queries to the agents in a pack, so a result's `name` arrives as `pack/Global/<query>`;
zeek._parse_line strips that prefix and types the record fleet_osquery.

What doesn't carry over: osquery's per-query `denylist: false` (bpf_connections, bpf_process_events). Fleet's
query spec has no such field, so through Fleet a restart that catches either query mid-run can skip it for a day,
and R22 doesn't watch Fleet's agents (a computer switched off is not a broken feed). Command-line flags (event publishers, the Sysmon channel) are set on each machine by
the installers, as in standalone mode.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CONF = ROOT / "agents/config/osquery.conf"
OUT = ROOT / "deploy/fleet/tapwatch.yml"

# Fleet's own agent options (v4.93): applying a config replaces them, so they are kept and ours added. The decorators
# put the agent's uuid and hostname on every result row, which is how tapwatch tells the computers apart.
FLEET_OPTIONS = {"disable_distributed": False, "distributed_interval": 10, "distributed_plugin": "tls",
                 "distributed_tls_max_attempts": 3, "logger_tls_endpoint": "/api/osquery/log", "logger_tls_period": 10,
                 "pack_delimiter": "/"}
# Startup flags rather than runtime options: Fleet refuses them in agent options. The installers' flag files set
# --host_identifier=uuid, and utc is osquery's default.
STARTUP_ONLY = {"host_identifier", "utc"}
DECORATORS = {"load": ["SELECT uuid AS host_uuid FROM system_info;", "SELECT hostname AS hostname FROM system_info;"]}

# osquery's platform words -> Fleet's (comma-separated; empty means every platform)
PLATFORMS = {"windows": "windows", "linux": "linux", "darwin": "darwin", "posix": "darwin,linux", "all": "", "": ""}


def logging_of(q: dict) -> str:
    if q.get("snapshot"):
        return "snapshot"
    return "differential" if q.get("removed", True) else "differential_ignore_removals"


def specs(conf: dict) -> list[dict]:
    out = [{"apiVersion": "v1", "kind": "config", "spec": {"agent_options": {
        "config": {"options": {**FLEET_OPTIONS, **{k: v for k, v in conf.get("options", {}).items()
                                                   if k not in STARTUP_ONLY}},
                   "decorators": DECORATORS,
                   "file_paths": conf.get("file_paths", {})},
        "overrides": {}}}}]
    for name, q in conf["schedule"].items():
        out.append({"apiVersion": "v1", "kind": "report", "spec": {  # Fleet 4.93 renamed queries to reports
            "name": name,
            "description": q.get("description", ""),
            "query": q["query"],
            "interval": q["interval"],
            "platform": PLATFORMS[q.get("platform", "")],
            "logging": logging_of(q),
            "automations_enabled": True,
            "discard_data": True,
            "observer_can_run": False,
        }})
    return out


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper, s: str):
    # Long SQL stays readable as a block, and every line round-trips exactly.
    return dumper.represent_scalar("tag:yaml.org,2002:str", s, style="|" if "\n" in s else None)


_Dumper.add_representer(str, _str)


def render(conf: dict) -> str:
    head = ("# Generated by tools/fleet_config.py from agents/config/osquery.conf; don't edit by hand.\n"
            "# Apply with: fleetctl apply -f deploy/fleet/tapwatch.yml\n")
    return head + "---\n".join(yaml.dump(s, Dumper=_Dumper, sort_keys=False, width=120, allow_unicode=True)
                               for s in specs(conf))


def main() -> int:
    sys.stdout.write(render(json.loads(CONF.read_text())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
